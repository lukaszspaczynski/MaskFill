// Generates the key material the paid-rule scheme relies on. Run once.
//
//   node tools/gen-keys.mjs
//
// Writes three things:
//   keys/signing-private.jwk  -- ECDSA P-256 private key. Signs paid rules.
//                                THE crown jewel; gitignored. Whoever holds it
//                                can mint rules the extension will trust.
//   keys/                     -- also keeps public + aes copies for reference.
//   src/crypto/keys.js        -- public verify key + AES key, embedded in the
//                                extension (they ship in it either way).
//
// The AES key only obfuscates rule contents; since it ships in every copy of
// the extension, a determined user can recover it. That is expected -- it stops
// casual copying, not a motivated reverse engineer. The ECDSA signature is the
// real guarantee: it decides which rules run, and its private half never ships.

import { webcrypto as crypto } from "node:crypto";
import { writeFileSync, mkdirSync } from "node:fs";

const b64 = (buf) => Buffer.from(buf).toString("base64");

mkdirSync("keys", { recursive: true });
mkdirSync("src/crypto", { recursive: true });

const signing = await crypto.subtle.generateKey(
  { name: "ECDSA", namedCurve: "P-256" },
  true,
  ["sign", "verify"]
);
const priv = await crypto.subtle.exportKey("jwk", signing.privateKey);
const pub = await crypto.subtle.exportKey("jwk", signing.publicKey);

const aes = await crypto.subtle.generateKey({ name: "AES-GCM", length: 256 }, true, [
  "encrypt",
  "decrypt",
]);
const aesRaw = b64(await crypto.subtle.exportKey("raw", aes));

writeFileSync("keys/signing-private.jwk", JSON.stringify(priv, null, 2));
writeFileSync("keys/signing-public.jwk", JSON.stringify(pub, null, 2));
writeFileSync("keys/aes.key", aesRaw + "\n");

const embedded = `// GENERATED by tools/gen-keys.mjs -- do not edit by hand.
//
// These ship inside the extension. The public key verifies paid-rule
// signatures; the AES key decrypts their contents. The matching PRIVATE signing
// key is not here and must never be committed -- see tools/gen-keys.mjs.

globalThis.MaskFillKeys = {
  verifyJwk: ${JSON.stringify(pub)},
  aesKey: ${JSON.stringify(aesRaw)},
};
`;
writeFileSync("src/crypto/keys.js", embedded);

console.log("wrote keys/ and src/crypto/keys.js");
console.log("private signing key: keys/signing-private.jwk (gitignored)");
